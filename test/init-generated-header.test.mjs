// A generated skill says it is generated and how to regenerate it (#300).
import { afterAll, beforeAll, describe, it, expect } from 'vitest';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { devNull, tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { initProject } from '../src/init/init.mjs';
import { REGENERATE_WITH, generatedByHeader, markSkill, prePushBlock, skillState } from '../src/init/managed.mjs';

const ROOT = new URL('..', import.meta.url).pathname;
const TEMPLATE = readFileSync(join(ROOT, 'src/init/templates/SKILL.md'), 'utf8');
const savedEnv = {};
beforeAll(() => { for (const k of ['GIT_CONFIG_GLOBAL', 'GIT_CONFIG_NOSYSTEM']) savedEnv[k] = process.env[k]; process.env.GIT_CONFIG_GLOBAL = devNull; process.env.GIT_CONFIG_NOSYSTEM = '1'; });
afterAll(() => { for (const [k, v] of Object.entries(savedEnv)) { if (v === undefined) delete process.env[k]; else process.env[k] = v; } });
const repo = () => {
  const dir = mkdtempSync(join(tmpdir(), 'tg-init-header-'));
  spawnSync('git', ['init', '-q'], { cwd: dir });
  spawnSync('git', ['config', 'core.hooksPath', '.githooks'], { cwd: dir });
  return dir;
};
const SKILL = '.claude/skills/testguard/SKILL.md';
const HEADER = (v) => `<!-- generated by testguard ${v}; regenerate with: testguard init --upgrade -->`;
const withoutHeader = (text) => text.split('\n').filter((l) => !l.startsWith('<!-- generated by testguard')).join('\n');

describe('the generated header on the skill (#300)', () => {
  it('a fresh install carries the header, right after the front matter and ahead of the marker', () => {
    const dir = repo();
    try {
      initProject({ projectDir: dir, toolVersion: '0.31.0' });
      const text = readFileSync(join(dir, SKILL), 'utf8');
      expect(text.split('\n').filter((l) => l.startsWith('<!-- generated by testguard'))).toEqual([HEADER('0.31.0')]);
      expect(text).toMatch(/\n---\n<!-- generated by testguard 0\.31\.0; regenerate with: testguard init --upgrade -->\n<!-- testguard:template \d+ sha256=[0-9a-f]+ -->\n/);
      expect(generatedByHeader('0.31.0')).toBe(HEADER('0.31.0'));
      expect(skillState(text, TEMPLATE)).toBe('current');
    } finally { rmSync(dir, { recursive: true, force: true }); }
  });

  it('--upgrade adds the header to an unmodified copy that has none, and only then', () => {
    const dir = repo();
    try {
      initProject({ projectDir: dir, toolVersion: '0.31.0' });
      const path = join(dir, SKILL);
      // What an older release wrote: the same marked skill, no header line.
      writeFileSync(path, withoutHeader(readFileSync(path, 'utf8')));
      expect(skillState(readFileSync(path, 'utf8'), TEMPLATE)).toBe('old');
      expect(initProject({ projectDir: dir, toolVersion: '0.31.0' }).outdated).toEqual([expect.stringMatching(/SKILL\.md: an older skill template, unmodified/)]);
      initProject({ projectDir: dir, upgrade: true, toolVersion: '0.31.0' });
      expect(readFileSync(path, 'utf8')).toBe(markSkill(TEMPLATE, '0.31.0'));
      // A later release does not rewrite a copy that already has the header.
      const before = readFileSync(path, 'utf8');
      const r = initProject({ projectDir: dir, upgrade: true, toolVersion: '0.32.0' });
      expect(readFileSync(path, 'utf8')).toBe(before);
      expect(r.skipped).toEqual(expect.arrayContaining([expect.stringMatching(/SKILL\.md is the current template/)]));
    } finally { rmSync(dir, { recursive: true, force: true }); }
  });

  it('an edited copy is left alone, with or without the header', () => {
    const dir = repo();
    try {
      initProject({ projectDir: dir, toolVersion: '0.31.0' });
      const path = join(dir, SKILL);
      const edited = withoutHeader(readFileSync(path, 'utf8')) + '\nOur own rule.\n';
      writeFileSync(path, edited);
      expect(skillState(edited, TEMPLATE)).toBe('modified');
      const r = initProject({ projectDir: dir, upgrade: true, toolVersion: '0.31.0' });
      expect(readFileSync(path, 'utf8')).toBe(edited);
      expect(r.skipped).toEqual(expect.arrayContaining([expect.stringMatching(/SKILL\.md exists and was edited/)]));
      const withHeader = markSkill(TEMPLATE, '0.31.0') + '\nOur own rule.\n';
      expect(skillState(withHeader, TEMPLATE)).toBe('modified');
    } finally { rmSync(dir, { recursive: true, force: true }); }
  });

  it('the header names the same regenerate command as the pre-push block', () => {
    expect(REGENERATE_WITH).toBe('testguard init --upgrade');
    expect(generatedByHeader('1.2.3')).toContain(`regenerate with: ${REGENERATE_WITH} -->`);
    expect(prePushBlock('.', { version: '0.31.0' })).toContain(`# Regenerated by \`${REGENERATE_WITH}\`; edit outside this block.`);
  });

  it('the shipped template files stay free of the header: it holds a version', () => {
    expect(TEMPLATE).not.toContain('generated by testguard');
  });
});
